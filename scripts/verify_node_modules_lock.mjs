import { constants } from "node:fs";
import { access, readFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import { fileURLToPath } from "node:url";

function parseArguments(argv) {
  let root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");

  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === "--root" && argv[index + 1]) {
      root = path.resolve(argv[index + 1]);
      index += 1;
      continue;
    }
    throw new Error(`unsupported argument: ${argument}`);
  }

  return { root };
}

async function readJson(filePath) {
  try {
    return JSON.parse(await readFile(filePath, "utf8"));
  } catch (error) {
    throw new Error(`cannot read valid JSON from ${filePath}: ${error.message}`);
  }
}

function declaredDependencyNames(manifest) {
  const names = new Set();
  for (const field of ["dependencies", "devDependencies", "optionalDependencies"]) {
    const dependencies = manifest[field];
    if (dependencies === undefined) {
      continue;
    }
    if (dependencies === null || typeof dependencies !== "object" || Array.isArray(dependencies)) {
      throw new Error(`package.json field ${field} must be an object`);
    }
    for (const name of Object.keys(dependencies)) {
      names.add(name);
    }
  }
  return [...names].sort();
}

function constraintAllows(rawValues, currentValue) {
  if (rawValues === undefined) {
    return true;
  }
  const values = Array.isArray(rawValues) ? rawValues : [rawValues];
  const normalized = values.map((value) => String(value));
  if (normalized.includes(`!${currentValue}`)) {
    return false;
  }
  const positive = normalized.filter((value) => !value.startsWith("!"));
  return positive.length === 0 || positive.includes(currentValue);
}

function currentLibcFlavor() {
  if (process.platform !== "linux") {
    return "";
  }
  return process.report?.getReport()?.header?.glibcVersionRuntime ? "gnu" : "musl";
}

function platformPackageMatches(lockKey, lockedPackage) {
  if (!constraintAllows(lockedPackage.os, process.platform) || !constraintAllows(lockedPackage.cpu, process.arch)) {
    return false;
  }
  const libc = currentLibcFlavor();
  if (!constraintAllows(lockedPackage.libc, libc)) {
    return false;
  }
  if (process.platform === "linux") {
    if (libc === "gnu" && lockKey.includes("-musl")) {
      return false;
    }
    if (libc === "musl" && /-(?:gnu|gnueabihf)(?:$|\/)/.test(lockKey)) {
      return false;
    }
  }
  return true;
}

async function installedVersion(packagePath) {
  try {
    const manifest = await readJson(path.join(packagePath, "package.json"));
    return manifest.version ?? "missing";
  } catch {
    return "missing";
  }
}

function executableNames(name, lockedPackage) {
  if (typeof lockedPackage.bin === "string") {
    return [name.split("/").at(-1)];
  }
  if (lockedPackage.bin && typeof lockedPackage.bin === "object" && !Array.isArray(lockedPackage.bin)) {
    return Object.keys(lockedPackage.bin);
  }
  return [];
}

async function verify(root) {
  const manifest = await readJson(path.join(root, "package.json"));
  const lockfile = await readJson(path.join(root, "package-lock.json"));
  if (lockfile.packages === null || typeof lockfile.packages !== "object") {
    throw new Error("package-lock.json must contain a packages object");
  }

  const names = declaredDependencyNames(manifest);
  const mismatches = [];
  let executableCount = 0;
  for (const name of names) {
    const lockKey = `node_modules/${name}`;
    const lockedPackage = lockfile.packages[lockKey] ?? {};
    const lockedVersion = lockedPackage.version ?? "missing";
    const currentInstalledVersion = await installedVersion(path.join(root, "node_modules", ...name.split("/")));

    if (lockedVersion !== currentInstalledVersion || lockedVersion === "missing") {
      mismatches.push(`${name} locked=${lockedVersion} installed=${currentInstalledVersion}`);
    }

    for (const executableName of executableNames(name, lockedPackage)) {
      executableCount += 1;
      const suffix = process.platform === "win32" ? ".cmd" : "";
      const executablePath = path.join(root, "node_modules", ".bin", `${executableName}${suffix}`);
      try {
        await access(executablePath, process.platform === "win32" ? constants.F_OK : constants.X_OK);
      } catch {
        mismatches.push(`executable shim ${executableName}${suffix} is missing or unusable for ${process.platform}`);
      }
    }
  }

  let platformNativeCount = 0;
  for (const [lockKey, lockedPackage] of Object.entries(lockfile.packages)) {
    if (
      !lockKey.startsWith("node_modules/") ||
      !lockedPackage?.optional ||
      (lockedPackage.os === undefined && lockedPackage.cpu === undefined && lockedPackage.libc === undefined) ||
      !platformPackageMatches(lockKey, lockedPackage)
    ) {
      continue;
    }
    platformNativeCount += 1;
    const lockedVersion = lockedPackage.version ?? "missing";
    const currentInstalledVersion = await installedVersion(path.join(root, ...lockKey.split("/")));
    if (lockedVersion !== currentInstalledVersion || lockedVersion === "missing") {
      const packageName = lockKey.slice(lockKey.lastIndexOf("node_modules/") + "node_modules/".length);
      mismatches.push(
        `platform-native ${packageName} locked=${lockedVersion} installed=${currentInstalledVersion} for ${process.platform}/${process.arch}`,
      );
    }
  }

  if (mismatches.length > 0) {
    throw new Error(
      `dependency state mismatch:\n- ${mismatches.join("\n- ")}\nRun npm ci from the current OS to restore package-lock.json state.`,
    );
  }

  process.stdout.write(
    `[deps] PASS: ${names.length} declared dependencies, ${executableCount} executable shims, and ${platformNativeCount} platform-native packages match package-lock.json.\n`,
  );
}

try {
  const { root } = parseArguments(process.argv.slice(2));
  await verify(root);
} catch (error) {
  process.stderr.write(`[deps] ERROR: ${error.message}\n`);
  process.exitCode = 1;
}
