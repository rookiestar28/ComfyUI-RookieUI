export const LANGUAGE_SELECTOR_VIEWPORT_MARGIN = 12;
export const LANGUAGE_SELECTOR_MAX_WIDTH = 360;
export const LANGUAGE_SELECTOR_MIN_WIDTH = 240;
export const LANGUAGE_SELECTOR_MAX_HEIGHT = 320;
export function getLanguageAliasKey(value) {
  return String(value ?? "").trim().replace(/_/g, "-").toLowerCase();
}

export function normalizeWorkbenchLanguageOptions(languageOptions) {
  const options = (Array.isArray(languageOptions) && languageOptions.length
    ? languageOptions
    : [{ code: "en", title: "English" }])
    .map((entry) => ({
      code: String(entry?.code ?? "en").trim() || "en",
      title: String(entry?.title ?? entry?.code ?? "English").trim() || "English",
      nativeTitle: String(entry?.native_title ?? entry?.nativeTitle ?? entry?.title ?? entry?.code ?? "English").trim() || "English",
      aliases: Array.isArray(entry?.aliases)
        ? entry.aliases.map((alias) => String(alias ?? "").trim()).filter(Boolean)
        : [],
      fallbackCode: String(entry?.fallback_code ?? entry?.fallbackCode ?? "en").trim() || "en",
    }))
    .filter((entry) => entry.code);
  return options.length ? options : [{ code: "en", title: "English", nativeTitle: "English", aliases: [], fallbackCode: "en" }];
}

export function createWorkbenchLanguageSupport(languageOptions, i18n = WORKBENCH_I18N) {
  const normalizedOptions = normalizeWorkbenchLanguageOptions(languageOptions);
  const aliases = new Map();
  normalizedOptions.forEach((entry) => {
    aliases.set(getLanguageAliasKey(entry.code), entry.code);
    entry.aliases.forEach((alias) => {
      aliases.set(getLanguageAliasKey(alias), entry.code);
    });
  });

  const getLanguageOptions = () => normalizedOptions;
  const normalizeLanguageCode = (value) => aliases.get(getLanguageAliasKey(value)) ?? aliases.get("en") ?? "en";
  const getLanguageOption = (code) => {
    const normalizedCode = getLanguageAliasKey(code);
    return normalizedOptions.find((entry) => getLanguageAliasKey(entry.code) === normalizedCode) ?? null;
  };

  const getWorkbenchI18nChain = (value) => {
    const chain = [];
    const seen = new Set();
    const append = (code) => {
      const normalizedCode = String(code ?? "").trim();
      if (!normalizedCode || seen.has(normalizedCode)) {
        return;
      }
      seen.add(normalizedCode);
      if (i18n[normalizedCode]) {
        chain.push(normalizedCode);
      }
    };

    let cursor = normalizeLanguageCode(value);
    for (let index = 0; index < 8 && cursor && !seen.has("fallback:" + cursor); index += 1) {
      seen.add("fallback:" + cursor);
      append(cursor);
      const option = getLanguageOption(cursor);
      const fallbackCode = normalizeLanguageCode(option?.fallbackCode ?? "");
      if (!fallbackCode || fallbackCode === cursor) {
        break;
      }
      cursor = fallbackCode;
    }

    const selectedLanguage = normalizeLanguageCode(value);
    const baseLanguage = selectedLanguage.includes("-") ? selectedLanguage.split("-")[0] : "";
    append(baseLanguage);
    append("en");
    return chain.length ? chain : ["en"];
  };

  const translate = (language, key) => {
    for (const code of getWorkbenchI18nChain(language)) {
      const value = i18n[code]?.[key];
      if (value !== undefined) {
        return value;
      }
    }
    return i18n.en?.[key] ?? key;
  };

  const format = (language, key, replacements = {}) =>
    Object.entries(replacements).reduce(
      (value, [name, replacement]) => value.replaceAll("{" + name + "}", String(replacement ?? "")),
      translate(language, key),
    );

  return {
    getLanguageOptions,
    normalizeLanguageCode,
    getLanguageOption,
    getWorkbenchI18nChain,
    translate,
    format,
  };
}

export function getViewportSize(globalScope = globalThis, documentNode = globalThis?.document) {
  const viewport = globalScope?.visualViewport;
  const width = Number(viewport?.width ?? globalScope?.innerWidth ?? documentNode?.documentElement?.clientWidth ?? 1024);
  const height = Number(viewport?.height ?? globalScope?.innerHeight ?? documentNode?.documentElement?.clientHeight ?? 768);
  return {
    width: Number.isFinite(width) && width > 0 ? width : 1024,
    height: Number.isFinite(height) && height > 0 ? height : 768,
  };
}

export function clampOverlayValue(value, min, max) {
  if (max < min) {
    return min;
  }
  return Math.min(Math.max(value, min), max);
}

export function computeLanguageSelectorPlacement(triggerRect, viewport) {
  const safeViewport = {
    width: Number(viewport?.width ?? 1024) || 1024,
    height: Number(viewport?.height ?? 768) || 768,
  };
  const rect = triggerRect ?? { left: LANGUAGE_SELECTOR_VIEWPORT_MARGIN, bottom: LANGUAGE_SELECTOR_VIEWPORT_MARGIN };
  const availableWidth = Math.max(160, safeViewport.width - LANGUAGE_SELECTOR_VIEWPORT_MARGIN * 2);
  const width = Math.min(
    LANGUAGE_SELECTOR_MAX_WIDTH,
    Math.max(LANGUAGE_SELECTOR_MIN_WIDTH, Math.min(availableWidth, Math.round(availableWidth))),
  );
  const left = clampOverlayValue(
    Math.round(Number(rect.left ?? LANGUAGE_SELECTOR_VIEWPORT_MARGIN)),
    LANGUAGE_SELECTOR_VIEWPORT_MARGIN,
    safeViewport.width - width - LANGUAGE_SELECTOR_VIEWPORT_MARGIN,
  );
  const topCandidate = Math.round(Number(rect.bottom ?? LANGUAGE_SELECTOR_VIEWPORT_MARGIN) + 6);
  const maxHeight = Math.min(
    LANGUAGE_SELECTOR_MAX_HEIGHT,
    Math.max(120, safeViewport.height - topCandidate - LANGUAGE_SELECTOR_VIEWPORT_MARGIN),
  );
  const top = clampOverlayValue(
    topCandidate,
    LANGUAGE_SELECTOR_VIEWPORT_MARGIN,
    safeViewport.height - maxHeight - LANGUAGE_SELECTOR_VIEWPORT_MARGIN,
  );
  return { left, top, width, maxHeight };
}

export function formatLanguageOptionLabel(entry) {
  const code = String(entry?.code ?? "en").trim() || "en";
  const title = String(entry?.title ?? code).trim() || code;
  const nativeTitle = String(entry?.nativeTitle ?? entry?.native_title ?? title).trim() || title;
  return nativeTitle && nativeTitle !== title ? code + " - " + title + " (" + nativeTitle + ")" : code + " - " + title;
}
